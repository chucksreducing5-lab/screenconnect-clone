function openBrowserSocket({ streamScreen }) {
  stopBrowserShareRequested = false;
  if (browserWs && (browserWs.readyState === WebSocket.OPEN || browserWs.readyState === WebSocket.CONNECTING)) {
    // If socket already exists and we are now starting streaming, immediately announce starting state.
    if (streamScreen && browserWs.readyState === WebSocket.OPEN) {
      const isMobileBroadcastClient = requiresNativeMobileBroadcast() || (isIosPlatform() && !supportsScreenCapture());
      browserWs.send(JSON.stringify({
        type: 'screen.broadcast.status',
        payload: {
          status: 'starting',
          platform: currentPlatform,
          screenCapture: supportsScreenCapture(),
          message: 'Customer approved screen broadcast. Waiting for the first screen frame.',
          requiresNativeApp: isIosPlatform() && !supportsScreenCapture(),
          mobileAppRequired: Boolean(requiresNativeMobileBroadcast()),
          mobileSupport: pendingMobileSupport || null,
          isMobileBroadcastClient
        }
      }));
      // Start the frame timer if it's not already running.
      if (typeof startBrowserFrameCapture === 'function') {
        startBrowserFrameCapture();
      }
    }
    return;
  }

  const desiredUrl = customerWebSocketUrl();
  if (browserWs && (browserWs.readyState === WebSocket.OPEN || browserWs.readyState === WebSocket.CONNECTING)) {
    if (browserWs.url === desiredUrl) {
      if (streamScreen && browserWs.readyState === WebSocket.OPEN) {
        const isMobileBroadcastClient = requiresNativeMobileBroadcast() || (isIosPlatform() && !supportsScreenCapture());
        browserWs.send(JSON.stringify({
          type: 'screen.broadcast.status',
          payload: {
            status: 'starting',
            platform: currentPlatform,
            screenCapture: supportsScreenCapture(),
            message: 'Customer approved screen broadcast. Waiting for the first screen frame.',
            requiresNativeApp: isIosPlatform() && !supportsScreenCapture(),
            mobileAppRequired: Boolean(requiresNativeMobileBroadcast()),
            mobileSupport: pendingMobileSupport || null,
            isMobileBroadcastClient
          }
        }));
        if (typeof startBrowserFrameCapture === 'function') {
          startBrowserFrameCapture();
        }
      }
      return;
    }
    browserWs.close(1000, 'Switching customer session');
  }

  browserWs = new WebSocket(desiredUrl);
  const browserSocket = browserWs;

  browserWs.addEventListener('open', () => {
    if (browserWs !== browserSocket) return;
    // Reset reconnection attempts on successful connection
    browserReconnectAttempts = 0;
    browserFirstFrameSent = false;
    const isMobileBroadcastClient = requiresNativeMobileBroadcast() || (isIosPlatform() && !supportsScreenCapture());
    const waitingStatus = streamScreen
      ? 'starting'
      : supportsScreenCapture()
        ? 'waiting'
        : 'unavailable';

    browserWs.send(JSON.stringify({
      type: 'screen.broadcast.status',
      payload: {
        status: waitingStatus,
        platform: currentPlatform,
        screenCapture: supportsScreenCapture(),
        message: streamScreen
          ? 'Customer approved screen broadcast. Waiting for the first screen frame.'
          : supportsScreenCapture()
            ? 'Customer connected. Tap Start Broadcast / Share Screen so the host can view this device.'
            : isIosPlatform()
              ? 'Customer connected. Open the iOS support app: Visit Host URL, Enter Code, Initiate ScreenShare, then Start Broadcast.'
              : 'Customer connected. Open the mobile support app and start screen broadcast to share the screen.',
        requiresNativeApp: isIosPlatform() && !supportsScreenCapture(),
        mobileAppRequired: Boolean(requiresNativeMobileBroadcast()),
        mobileSupport: pendingMobileSupport || null,
        isMobileBroadcastClient
      }
    }));

    clearInterval(browserHeartbeatTimer);
    browserHeartbeatTimer = setInterval(() => {
      if (!browserWs || browserWs.readyState !== WebSocket.OPEN) return;
      browserWs.send(JSON.stringify({
        type: 'screen.heartbeat',
        payload: {
          platform: currentPlatform,
          status: browserFirstFrameSent ? 'live' : 'waiting_first_frame',
          transport: requiresNativeMobileBroadcast() ? 'native-mobile-app' : 'browser-share'
        }
      }));
    }, 5000);

    if (streamScreen) {
      startBrowserFrameCapture();
    }
  });

  browserWs.addEventListener('message', (event) => {
    if (browserWs !== browserSocket) return;
    let messageData;
    try {
      messageData = JSON.parse(event.data);
    } catch {
      return;
    }

    if (messageData.type === 'blank-screen') {
      setBlankScreen(messageData.payload);
      return;
    }

    if (messageData.type === 'session.end') {
      stopBrowserShare();
      return;
    }

    // Mobile/broadcast recovery signals from the relay.
    if (messageData.type === 'screen.broadcast.status') {
      const payload = messageData.payload || {};
      const status = String(payload.status || '').toLowerCase();

      if (status === 'reconnect_required' || status === 'stream_stale') {
        setMessage(status === 'reconnect_required' ? 'Mobile broadcast reconnect required.' : 'Mobile broadcast became stale.');
        controlMessage.textContent =
          status === 'reconnect_required'
            ? (payload?.requiresNativeApp ? 'Restart the broadcast in the iOS/Android support app.' : 'Restart the broadcast on the customer device.')
            : 'Ask the customer to reopen the support app and restart the screen broadcast.';

        // If the session is still valid, re-surface the deep link so the user can restart quickly.
        if (activeSessionId && activeCustomerToken) {
          const href = mobileAppDeepLink(activeSessionId, activeCustomerToken)
            || mobileAppFallbackUrl(activeSessionId, activeCustomerToken);
          if (href && href !== '#') {
            if (mobileAppFallback) mobileAppFallback.hidden = false;
            if (mobileAppLink) {
              mobileAppLink.href = href;
              mobileAppLink.textContent = `Start Broadcast in ${mobileAppName()}`;
            }
          }
        }

        // If we were browser-sharing (possible on platforms with screen capture),
        // allow the existing WS reconnect logic to resume; avoid restarting
        // screen capture automatically here.
        browserFirstFrameSent = false;
      }

      return;
    }

    // Some recovery paths may send an explicit kill/restart request.
    if (messageData.type === 'screen.broadcast.kill') {
      const reason = String(messageData?.payload?.reason || messageData?.payload?.message || 'broadcast.kill');
      setMessage('Broadcast interrupted. Restarting is required.');
      controlMessage.textContent = `Broadcast was interrupted. Restart broadcast in the customer app. Reason: ${reason}`;

      browserFirstFrameSent = false;

      // Do not hard-stop the browser frame capture here; just inform the user
      // and let the normal reconnect path + native restart recover.
      return;
    }

    // Host (technician) connected to this session: prompt the customer for
    // consent and, on approval, start screen broadcast. This is the signal
    // that un-sticks the mobile flow — without it the page just shows static
    // instructions and the technician never receives the customer's screen.
    if (messageData.type === 'host.connected') {
      showHostConsentPrompt(messageData.payload || {});
      return;
    }
    if (messageData.type === 'peer.connected' && messageData.payload?.role === 'agent') {
      showHostConsentPrompt(messageData.payload || {});
      return;
    }
  });

  browserWs.addEventListener('close', () => {
    if (browserWs !== browserSocket) return;
    clearInterval(browserFrameTimer);
    browserFrameTimer = null;
    clearInterval(browserHeartbeatTimer);
    browserHeartbeatTimer = null;

    if (stopBrowserShareRequested) {
      stopBrowserShareRequested = false;
      return;
    }

    // Attempt to reconnect signaling channel if we still have an active session.
    // Do not depend on downloadPanel visibility: that can prevent reconnect during
    // mobile/browser flows where the download panel is hidden.
    if (activeSessionId && activeCustomerToken) {
      // Exponential backoff with jitter
      const attempt = browserReconnectAttempts++;
      const baseDelay = Math.min(BASE_BROWSER_RECONNECT_DELAY_MS * Math.pow(2, attempt), MAX_BROWSER_RECONNECT_DELAY_MS);
      const jitter = Math.random() * 0.3 * baseDelay; // 0-30% jitter
      const delay = Math.floor(baseDelay + jitter);
      
      if (browserReconnectTimer) clearTimeout(browserReconnectTimer);
      browserReconnectTimer = window.setTimeout(() => {
        browserReconnectTimer = null;
        if (browserWs && (browserWs.readyState === WebSocket.OPEN || browserWs.readyState === WebSocket.CONNECTING)) return;
        // If we were already sharing, try to resume if the stream is still active.
        const shouldResumeStream = Boolean(browserStream && browserStream.active);
        if (browserFirstFrameSent && !shouldResumeStream) {
          setMessage('Screen broadcast stopped.');
          browserFirstFrameSent = false;
        }
        openBrowserSocket({ streamScreen: shouldResumeStream });
      }, delay);
    }
  });
}

function startBrowserFrameCapture() {
  if (browserFrameTimer) clearInterval(browserFrameTimer);

  controlMessage.textContent = 'Broadcast permission approved. Starting screen frames...';
  setMessage('');

  const canvas = document.createElement('canvas');
  const context = canvas.getContext('2d');

  let lastFrameData = '';
  browserFrameTimer = setInterval(() => {
    if (!context || browserWs?.readyState !== WebSocket.OPEN) return;

    // Ensure video is actually playing and has dimensions before capturing.
    if (!localVideo || localVideo.paused || localVideo.ended || !localVideo.videoWidth) return;

    const maxWidth = 1920;
    const scale = Math.min(1, maxWidth / localVideo.videoWidth);
    canvas.width = Math.max(1, Math.round(localVideo.videoWidth * scale));
    canvas.height = Math.max(1, Math.round(localVideo.videoHeight * scale));

    // Use better interpolation for canvas scaling if available
    context.imageSmoothingEnabled = true;
    context.imageSmoothingQuality = 'high';
    context.drawImage(localVideo, 0, 0, canvas.width, canvas.height);

    const dataUrl = canvas.toDataURL('image/jpeg', 0.90);
    const data = dataUrl.slice(dataUrl.indexOf(',') + 1);

    if (data === lastFrameData) return;
    lastFrameData = data;

    browserWs.send(JSON.stringify({
      type: 'screen.frame',
      payload: {
        format: 'jpeg',
        data,
        sequence: browserFrameSequence++
      }
    }));

    if (!browserFirstFrameSent) {
      browserFirstFrameSent = true;
      browserWs.send(JSON.stringify({
        type: 'screen.broadcast.status',
        payload: {
          status: 'live',
          platform: currentPlatform,
          message: 'Mobile screen broadcast is live.'
        }
      }));
      showSuccess();
      successMessage.textContent = 'You have successfully connected to your session.';
      successDetail.textContent = 'Keep this page open while your screen is shared with the technician. Close this page to disconnect.';
      if (browserShare) { browserShare.textContent = 'Broadcasting'; browserShare.disabled = true; }
    }
  }, 100);
}

async function startBrowserShare() {

  if (!activeSessionId || !activeCustomerToken) {
    setMessage('Enter the support code first.');
    return;
  }

  if (!supportsScreenCapture() || !navigator.mediaDevices?.getDisplayMedia) {
    stopBrowserShare();
    setMessage('Screen broadcast is not available in this browser view. Tap "Start Broadcast" to trigger the app native screen sharing.');
    controlMessage.textContent = isIosPlatform()
      ? 'On iPhone/iPad, the web view cannot share the full device screen. Tap "Start Broadcast" to open the support app and share your screen.'
      : 'Tap "Start Broadcast" to open the support app and share your screen.';
    throw new Error('Screen broadcast is not available in this browser view.');
  }

  stopBrowserShare();
  if (browserShare) { browserShare.disabled = true; browserShare.textContent = 'Starting broadcast...'; }
  setMessage('Choose the screen or phone display to share.');
  browserStream = await navigator.mediaDevices.getDisplayMedia({
    video: { frameRate: 10 },
    audio: false
  });

  if (localVideo) {
    localVideo.srcObject = browserStream;
    localVideo.hidden = false;
    localVideo.classList.add('is-visible');
    await localVideo.play().catch(() => {});
  }

  const [track] = browserStream.getVideoTracks();
  track?.addEventListener('ended', stopBrowserShare);

  openBrowserSocket({ streamScreen: true });
}

async function fetchTroubleshooting() {
  if (!activeSessionId || !activeCustomerToken) return null;
  try {
    const url = `/api/session/${encodeURIComponent(activeSessionId)}/troubleshooting?token=${encodeURIComponent(activeCustomerToken)}`;
    const res = await fetch(url);
    if (!res.ok) return null;
    return await res.json();
  } catch {
    return null;
  }
}

function troubleshootingMessage(data) {
  if (!data?.ok) return '';
  const session = data.session || {};
  if (data.lastJoinError) return `Remote support session not connecting: ${data.lastJoinError}`;
  if (session.permanentAccess && !session.permanentAccessAuthorizedAt) {
    return 'Authorization is still required before unattended access can start.';
  }
  if (isMobilePlatform()) {
    if (session.customerScreenStatus === 'ios_broadcast_connected_waiting_first_frame') {
      return `iPhone connected but no screen frames yet. Tap "Start Broadcast" above to open the support app and start sharing your screen.`;
    }
    if (session.customerScreenStatus === 'android_broadcast_connected_waiting_first_frame') {
      return `Android connected but no screen frames yet. Tap "Start Broadcast" above to open the support app and start sharing your screen.`;
    }
    if (session.customerScreenStatus === 'reconnect_required' || session.customerScreenStatus === 'stream_stale') {
      return 'Mobile broadcast disconnected/stale. Re-open the app and restart screen broadcast.';
    }
  }
  if (session.nativeClaimed && !session.nativeConnected) {
    return 'Client started but has not connected yet. Check firewall, antivirus, SSL/TLS, and reverse proxy WebSocket settings.';
  }
  if (session.blankScreen) return 'The remote screen is currently blanked by the technician.';
  if (session.permissions?.input === false) return 'Remote keyboard and mouse input is currently suspended.';
  return data.guidance?.ifStuckConnecting || '';
}

async function pollNativeConnection() {
  if (!activeSessionId || !activeCustomerToken) return;

  const statusPath = `/api/session/${encodeURIComponent(activeSessionId)}/customer-status?token=${encodeURIComponent(activeCustomerToken)}`;

  let response;
  try {
    response = await fetch(statusPath, {
      headers: { Accept: 'application/json' }
    });
  } catch {
    if (downloadPanel && !downloadPanel.hidden) {
      controlMessage.textContent = 'Could not reach the support server. Check internet, firewall, or security software, then retry.';
    }
    return;
  }

  if (response.status === 401 || response.status === 404) {
    safeLocalStorageRemove('remoteSupportLastJoin');
    activeSessionId = '';
    activeCustomerToken = '';
    joinForm.hidden = false;
    downloadPanel.hidden = true;
    successPanel.hidden = true;
    setMessage('This support link is no longer valid. Enter the current code from your technician.');
    join.disabled = false;
    clearInterval(nativePoll);
    return;
  }

  if (!response.ok) return;

  const contentType = String(response.headers.get('content-type') || '').toLowerCase();
  if (!contentType.includes('application/json')) {
    if (downloadPanel && !downloadPanel.hidden) {
      controlMessage.textContent = 'Unexpected response from support server. Please retry, or ask your technician to verify server/domain health.';
    }
    return;
  }

  let data;
  try {
    data = await response.json();
  } catch {
    if (downloadPanel && !downloadPanel.hidden) {
      controlMessage.textContent = 'Could not read session status response. Please retry.';
    }
    return;
  }

  if (data.nativeConnected) {
    showSuccess();
    if (successMessage && successDetail) {
      if (isMobilePlatform()) {
        successMessage.textContent = 'You have successfully joined the session.';
        successDetail.textContent = isIosPlatform()
          ? 'Your iPhone/iPad screen is now being shared with the technician. Keep this page open until the technician ends the session.'
          : 'Your phone screen is now being shared with the technician. Keep this page open until the technician ends the session.';
      } else {
        successMessage.textContent = 'You have successfully connected to your session.';
        successDetail.textContent = 'Keep this page open while your screen is shared with the technician. Close this page to disconnect.';
      }
    }
    controlMessage.textContent = isMobilePlatform()
      ? 'Mobile screen broadcast connected. Keep this page open while the technician is assisting.'
      : 'Support client connected. Keep this window open while the technician is assisting.';
    return;
  }

  // Enhanced mobile connect workflow guidance:
  // server status comes primarily from polling (customer-status) for iOS/Android.
  // Ensure the deep link panel is visible and actionable for:
  // - waiting_first_frame (iOS/Android connected but first screen.frame not received)
  // - reconnect_required / stream_stale
  if (isMobilePlatform()) {
    const s = String(data.customerScreenStatus || '').toLowerCase();
    const needsMobileRestart = ['reconnect_required', 'stream_stale'].includes(s);
    const waitingFirstFrame = ['ios_broadcast_connected_waiting_first_frame', 'android_broadcast_connected_waiting_first_frame'].includes(s);

    if (needsMobileRestart || waitingFirstFrame) {
      // Always show the app link UI on mobile so the customer can restart broadcast quickly.
      if (mobileAppFallback && mobileAppLink) {
        mobileAppFallback.hidden = false;
        if (activeSessionId && activeCustomerToken) {
          const href = mobileAppDeepLink(activeSessionId, activeCustomerToken)
            || mobileAppFallbackUrl(activeSessionId, activeCustomerToken);
          if (href && href !== '#') {
            mobileAppLink.href = href;
            mobileAppLink.textContent = `Start Broadcast in ${mobileAppName()}`;
          }
        }
      }

      const joinCodeText = effectiveJoinCode();
      const hostUrl = joinHostUrl();

      if (waitingFirstFrame) {
        setMessage(isIosPlatform() ? 'iPhone connected. Start broadcast to send frames.' : 'Android connected. Start screen sharing to send frames.');
        controlMessage.textContent = `Tap "Start Broadcast" above to open the support app and start sharing your screen. Support code: ${joinCodeText}.`;

        // Try to guide the user to the app again if they haven’t switched yet.
        window.setTimeout(() => {
          if (document.hidden) return;
          // If they haven't started broadcast yet, re-surface the deep link.
          // (We do not force-open without user gesture.)
          if (mobileAppLink && mobileAppLink.href && mobileAppLink.href !== '#') {
            mobileAppLink.textContent = `Start Broadcast in ${mobileAppName()} (tap to restart)`;
          }
        }, 2000);
      }

      if (needsMobileRestart) {
        setMessage('Broadcast interruption detected. Restart broadcast in the app.');
        controlMessage.textContent = `Restart the screen broadcast in ${mobileAppName()}, then keep the app foregrounded.`;

        // Update the deep link button copy to make restart obvious.
        if (mobileAppLink) mobileAppLink.textContent = `Start Broadcast in ${mobileAppName()} (tap to restart)`;
      }

      // Keep polling; host will transition once the first frame arrives.
      return;
    }
  }

  if (data.nativeClaimed) {
    setMessage('Support client installer started');
    controlMessage.textContent = 'Client stuck on connecting: keep the customer support app open while the remote support session connects.';
    return;
  }

  if (data.lastJoinError) {
    setMessage('Join failed');
    controlMessage.textContent = `Remote support session not connecting: ${data.lastJoinError}`;
    return;
  }

  if (downloadPanel && !downloadPanel.hidden) {
    if (joinStartedAt && Date.now() - joinStartedAt > 15000) {
      const diagnostics = await fetchTroubleshooting();
      const diagnosticMessage = troubleshootingMessage(diagnostics);
      controlMessage.textContent = diagnosticMessage || 'Connection troubleshooting: client stuck on connecting. Check firewall blocking remote support client, antivirus blocking remote support application, SSL/TLS certificate mismatch, or Cloudflare reverse proxy WebSocket issue.';
    }
  }
}

