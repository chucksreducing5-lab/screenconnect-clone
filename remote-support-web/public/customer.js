function normalizeEnteredCode(raw) {
  const value = String(raw || '').trim();
  if (!value) return '';

  const numeric = value.replace(/\D+/g, '').slice(0, 12);
  if (numeric) return numeric;

  return value
    .replace(/\s+/g, '')
    .replace(/[^a-zA-Z0-9-]/g, '')
    .slice(0, 16);
}

async function joinSession() {
  stopBrowserShare();

  const enteredCode = code.value;
  const sessionId = normalizeEnteredCode(enteredCode);
  if (!sessionId) {
    setMessage('Enter the support code first.');
    return;
  }

  code.value = sessionId;
  join.disabled = true;
  setMessage('Checking support code...');

  const attemptedAt = Date.now();
  const joinEndpoint = `/api/session/${encodeURIComponent(sessionId)}/join`;
  safeLocalStorageSet('remoteSupportLastAttemptedCode', sessionId);

  let response;
  const payload = {
    platform: currentPlatform,
    capabilities: clientCapabilities()
  };

  try {
    response = await fetch(joinEndpoint, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload)
    });
  } catch {
    response = null;
  }

  if (!response || !response.ok) {
    try {
      response = await fetch(joinEndpoint, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload)
      });
    } catch {
      response = null;
    }
  }

  if (!response) {
    join.disabled = false;
    throw new Error('Could not reach support server. Check connection and try again.');
  }

  const data = await response.json().catch(() => ({}));
  if (!response.ok) {
    join.disabled = false;
    if (response.status === 428 && data.code === 'PERMANENT_ACCESS_AUTHORIZATION_REQUIRED') {
      const isPermanentFlow = Boolean(data.permanentAccess);
      if (isPermanentFlow && data.authorizationToken) {
        activeSessionId = data.sessionId;
        activeCustomerToken = data.customerJoinToken;
        setupLauncherName = data.setupFileName || setupLauncherName;
        pendingPermanentAccess = true;
        pendingAuthorizationToken = data.authorizationToken;
        rememberJoin(sessionId, {
          sessionId: data.sessionId,
          customerJoinToken: data.customerJoinToken,
          setupFileName: setupLauncherName,
          permanentAccess: true,
          authorizationToken: pendingAuthorizationToken,
          downloadUrl: ''
        });

        joinForm.hidden = false;
        downloadPanel.hidden = true;
        successPanel.hidden = true;
        join.disabled = false;
        setMessage('Authorization required for unattended access');
        controlMessage.textContent = 'This session is configured for unattended/permanent access. Check the authorization box to continue.';
        updateAccessConsentUi(true);
        return;
      }

      throw new Error(data?.message || 'Session requires authorization before unattended access can continue.');
    }

    throw new Error(data?.message || 'Support code was not found.');
  }
  activeSessionId = data.sessionId;
  activeCustomerToken = data.customerJoinToken;
  setupLauncherName = data.setupFileName || setupLauncherName;
  pendingDownloadUrl = data.downloadUrl || '';
  pendingAlternateDownloadUrl = data.alternateDownloadUrl || '';
  pendingDmgUrl = data.dmgUrl || '';
  pendingAlternateDmgUrl = data.alternateDmgUrl || '';
  pendingMobileSupport = data.mobileSupport || null;
  updateAccessConsentUi(data.permanentAccess);

  // Hard reset: ensure the poll uses the newly joined session+token.
  rememberJoin(sessionId, { ...data, authorizationToken: pendingAuthorizationToken });

  if (prefersBrowserJoin()) {
    showBrowserJoinPanel(data);
    join.disabled = false;

    if (isIosPlatform()) {
      controlMessage.textContent = `Tap "Start Broadcast" below to open ${mobileAppName()} and share your screen. Support code: ${effectiveJoinCode()}.`;
      setMessage(`Tap "Start Broadcast" to open ${mobileAppName()} and share your screen.`);
    } else if (currentPlatform === 'android') {
      controlMessage.textContent = `Tap "Start Broadcast" below to open ${mobileAppName()} and share your screen. Support code: ${effectiveJoinCode()}.`;
      setMessage(`Tap "Start Broadcast" to open ${mobileAppName()} and share your screen.`);
    }

    if (isMobilePlatform()) {
      clearInterval(nativePoll);
      nativePoll = setInterval(() => pollNativeConnection().catch(() => {}), 2000);
      // Auto-launch this project's native support app (supportdesk://join) so
      // the customer gets the native "Start Broadcast" prompt immediately after
      // tapping the Join arrow, instead of being left on a static button that
      // never opens the app. Mirrors the ?code= and ?broadcast=1 auto-launch
      // paths above. The browser signaling WS stays open alongside the app.
      if (activeSessionId && activeCustomerToken &&
          (pendingMobileSupport?.launchNativeApp || requiresNativeMobileBroadcast())) {
        window.setTimeout(() => {
          try {
            if (launchMobileSupportApp({ force: true })) surfaceMobileAppInstallGuidance();
          } catch {}
        }, 600);
      }
    }
    return;
  }

  if (!data.downloadUrl) {
    showBrowserJoinPanel(data);
    join.disabled = false;
    setMessage('Support code accepted.');
    return;
  }

  joinForm.hidden = true;
  downloadPanel.hidden = false;
  successPanel.hidden = true;

  const isMac = currentPlatform === 'macos';
  const prompt = isMac ? 'macOS security prompts' : 'Windows UAC';

  controlMessage.textContent = data.permanentAccess
    ? `Start unattended access only with explicit authorization. Download and open ${setupLauncherName}, then approve ${prompt} only if you requested this remote support session.`
    : `Open ${setupLauncherName}, approve ${prompt} only if you requested this remote support session, and keep the customer support app open.`;

  joinModeTitle.textContent = isMac ? 'macOS support client installer' : 'Windows support client installer';
  stepOneText.textContent = isMac
    ? 'Your browser should download the remote support client. Open the DMG file and run the application to start the session.'
    : 'Your browser should download the remote support client. Open the downloaded file to start the session.';
  stepTwoText.textContent = isMac
    ? 'Approve the macOS security prompts for Accessibility and Screen Recording only if you recognize this technician and requested remote support.'
    : 'Approve the Windows UAC prompt only if you recognize this technician and requested remote support.';

  const protectedText = protectedStep?.querySelector('p');
  if (protectedText) {
    protectedText.textContent = isMac
      ? 'If macOS shows a security warning, ensure you recognize your technician before choosing to continue. Follow the on-screen prompts to allow the support session.'
      : 'If Windows shows a security warning, ensure you recognize your technician before choosing to continue. Follow the on-screen prompts to allow the support session.';
  }

  downloadHelp.textContent = 'Connection troubleshooting: if the client is stuck on connecting, retry the download or ask your technician to check firewall, antivirus, SSL/TLS, or reverse proxy WebSocket settings.';
  setWindowsInstallHelpVisible(true);
  setupDownload.hidden = false;
  setupDownload.textContent = isMac ? 'Download macOS DMG' : 'Download Windows EXE';
  msiDownload.hidden = isMac;
  setupDownload.href = data.downloadUrl || '#';
  if (zipDownload) {
    zipDownload.href = data.zipUrl || '#';
    zipDownload.hidden = !data.zipUrl || isMac;
  }
  if (setupLauncherName) setupDownload.setAttribute('download', setupLauncherName);
  if (msiDownload) msiDownload.href = data.msiUrl || data.alternateMsiUrl || data.downloadUrl || data.alternateDownloadUrl || '#';
  if (zipDownload && data.zipUrl) zipDownload.setAttribute('download', setupLauncherName.replace(/\.exe$/i, '.zip'));
  setMessage('');

  startDownload(data.downloadUrl);
  clearInterval(nativePoll);
  nativePoll = setInterval(() => pollNativeConnection().catch(() => {}), 2000);
}


