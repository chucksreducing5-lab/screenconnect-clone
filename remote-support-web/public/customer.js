function mobileAppFallbackUrl(sessionId, token) {
  // Fallback href for the Start Broadcast button. Prefer this project's own
  // supportdesk:// deep link (our mobile app) or a web broadcast URL. Never
  // fall back to screenconnect:// — that launches the real ConnectWise Control
  // app, whose guest JS crashes against this non-ScreenConnect relay with
  // "null is not an object (evaluating 'browsershare.hidden = isMobile')".
  if (pendingMobileSupport?.deepLinkScheme) return pendingMobileSupport.deepLinkScheme;
  if (pendingMobileSupport?.broadcastUrl) return pendingMobileSupport.broadcastUrl;
  if (pendingMobileSupport?.universalLink) return pendingMobileSupport.universalLink;
  try {
    const url = new URL('/customer', stableOrigin());
    url.searchParams.set('broadcast', '1');
    url.searchParams.set('sessionId', sessionId);
    url.searchParams.set('token', token);
    url.searchParams.set('platform', currentPlatform);
    url.searchParams.set('client', (currentPlatform === 'iphone' || currentPlatform === 'ipad') ? 'ios-mobile-broadcast' : 'android-mobile-broadcast');
    return url.toString();
  } catch {
    return '#';
  }
}

