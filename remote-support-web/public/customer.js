// Fetch public sessions (guest-safe)
let publicSessionsLoaded = false;
async function fetchPublicSessions() {
  if (!publicSessionSelect) return;
  if (publicSessionsLoaded) return;

  publicSessionsLoaded = true;
  publicSessionSelect.innerHTML = '';
  const loadingOpt = document.createElement('option');
  loadingOpt.value = '';
  loadingOpt.textContent = 'Loading…';
  publicSessionSelect.appendChild(loadingOpt);

  try {
    const res = await fetch('/api/guest/public-sessions', { credentials: 'same-origin' });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const data = await res.json();
    const sessions = Array.isArray(data?.sessions) ? data.sessions : [];

    publicSessionSelect.innerHTML = '';
    if (!sessions.length) {
      const opt = document.createElement('option');
      opt.value = '';
      opt.textContent = 'No public sessions available';
      publicSessionSelect.appendChild(opt);
      if (publicJoinMessage) publicJoinMessage.textContent = 'No public sessions to join right now.';
      return;
    }

    for (const s of sessions) {
      const opt = document.createElement('option');
      const displayName = s.displayName || s.sessionId || s.joinCode || 'Session';
      opt.value = String(s.joinCode || '');
      opt.textContent = `${displayName} (${s.joinCode})`;
      publicSessionSelect.appendChild(opt);
    }

    if (publicJoinMessage) publicJoinMessage.textContent = 'Select a session and continue.';
  } catch {
    publicSessionSelect.innerHTML = '';
    const opt = document.createElement('option');
    opt.value = '';
    opt.textContent = 'Could not load public sessions';
    publicSessionSelect.appendChild(opt);
    if (publicJoinMessage) publicJoinMessage.textContent = 'Unable to load public sessions. Try again later.';
  }
}

