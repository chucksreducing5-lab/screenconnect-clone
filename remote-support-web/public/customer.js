// When the customer page is loaded with `-broadcast=1&sessionId=...&token=...&client=...`
// (the universal web URL emitted by server.js's mobileSupportLinks), the page
// must coexist with this project's mobile support app so the two do not boot
// each other off the WebSocket:
//
//   * This page is treated as a 'browser-broadcast' signaling socket. Its only
//     purpose is to tell the host "the customer is here, wait for frames" and
//     to surface the deep-link CTA that launches the native app.
//
//   * The native app, when launched, opens its own WS as 'ios-mobile-broadcast'
//     / 'android-mobile-broadcast' and delivers the actual screen.frame
//     payloads. The host relays those frames to the technician viewer.
//
// Without this split, both sockets claim 'ios-mobile-broadcast', the server
// keeps kicking the older one out, and no frames ever reach the host.
if (broadcastMode && sessionIdFromUrl && customerTokenFromUrl) {
  window.addEventListener('load', () => {
    activeSessionId = sessionIdFromUrl;
    activeCustomerToken = customerTokenFromUrl;

    const targetClient = String(params.get('client') || '').toLowerCase();
    if (!pendingMobileSupport) {
      pendingMobileSupport = {
        broadcastUrl: location.href,
        websocketClient: targetClient || (isIosPlatform() ? 'ios-mobile-broadcast' : (currentPlatform === 'android' ? 'android-mobile-broadcast' : 'mobile-broadcast')),
        platform: String(params.get('platform') || currentPlatform)
      };
    }
    rememberJoin(sessionIdFromUrl, {
      sessionId: sessionIdFromUrl,
      customerJoinToken: customerTokenFromUrl
    });

    downloadPanel.hidden = false;
    successPanel.hidden = true;
    joinForm.hidden = true;
    if (mobileAppFallback) {
      mobileAppFallback.hidden = !isMobilePlatform();
      if (mobileAppLink) {
        mobileAppLink.href = mobileAppDeepLink(activeSessionId, activeCustomerToken)
          || mobileAppFallbackUrl(activeSessionId, activeCustomerToken);
        mobileAppLink.textContent = `Start Broadcast in ${mobileAppName()}`;
      }
      if (mobileBroadcastLink) {
        mobileBroadcastLink.href = pendingMobileSupport?.broadcastUrl
          || mobileBroadcastUrl(activeSessionId, activeCustomerToken);
        mobileBroadcastLink.textContent = 'Open helpsupport.top';
      }
      if (mobileAppDetail) {
        mobileAppDetail.textContent = `Tap "Start Broadcast" to open ${mobileAppName()} and share your screen. Support code: ${effectiveJoinCode()}.`;
      }
    }

    const nativeClientLabel = targetClient
      || (isIosPlatform() ? 'ios-mobile-broadcast' : (currentPlatform === 'android' ? 'android-mobile-broadcast' : 'mobile-broadcast'));
    setMessage(
      isIosPlatform()
        ? 'iPhone ready — tap Start Broadcast to open the support app and share your screen.'
        : currentPlatform === 'android'
          ? 'Android ready — tap Start Broadcast to open the support app and share your screen.'
          : 'Mobile device ready — tap Start Broadcast to open the support app and share your screen.'
    );
    controlMessage.textContent = `This page is signaling as client=browser-broadcast. The ${mobileAppName()} app will deliver frames as client=${nativeClientLabel}.`;

    // Open the WS as a 'browser-broadcast' (signaling only) client. Do not call
    // startBrowserFrameCapture — iOS Safari and Android Chrome cannot capture
    // the full phone screen from a web page; the native app owns that path.
    try {
      openBrowserSocket({ streamScreen: false });
    } catch {}

    // Auto-trigger the deep-link so the customer lands inside the native app
    // with one tap. We never close the browser signaling WS; both sockets stay
    // open simultaneously and the host sees both peers connected.
    if (pendingMobileSupport?.deepLink || pendingMobileSupport?.broadcastUrl) {
      window.setTimeout(() => {
        try {
          if (launchMobileSupportApp({ force: true })) surfaceMobileAppInstallGuidance();
        } catch {}
      }, 900);
    }
  });
}

