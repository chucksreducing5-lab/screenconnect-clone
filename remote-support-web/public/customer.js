function launchMobileSupportApp({ force = false } = {}) {
  if (!isMobilePlatform()) return false;
  if (!force && !requiresNativeMobileBroadcast()) return false;
  if (!activeSessionId || !activeCustomerToken) return false;

  const scDeepLink = mobileAppDeepLink(activeSessionId, activeCustomerToken);
  if (!scDeepLink) return false;

  if (supportsScreenCapture() && !isInThirdPartyWKWebView()) {
    return false;
  }

  if (isInThirdPartyWKWebView()) {
    setMessage('Open in Safari to start broadcasting');
    if (controlMessage) {
      controlMessage.textContent =
        `You\u2019re inside an in-app browser. Tap \u201cStart Broadcast\u201d below \u2014 ` +
        `it will open in Safari where ${mobileAppName()} can launch and request screen sharing permission. ` +
        `Or tap your browser\u2019s share button \u2197 and choose \u201cOpen in Safari\u201d.`;
    }
    if (mobileAppDetail) {
      mobileAppDetail.textContent =
        `Tap \u201cStart Broadcast\u201d to open ${mobileAppName()} via Safari and share your screen.`;
    }
    if (mobileAppLink) {
      mobileAppLink.href = scDeepLink;
      mobileAppLink.textContent = 'Start Broadcast';
    }
    if (mobileAppFallback) mobileAppFallback.hidden = false;
    return false;
  }

  setMessage(`Starting broadcast in ${mobileAppName()}...`);
  try {
    window.location.href = scDeepLink;
    return true;
  } catch {}

  try {
    const popup = window.open(scDeepLink, '_blank', 'noopener');
    if (popup) return true;
  } catch {}

  try {
    const iframe = document.createElement('iframe');
    iframe.style.display = 'none';
    iframe.src = scDeepLink;
    document.body.appendChild(iframe);
    setTimeout(() => { try { document.body.removeChild(iframe); } catch {} }, 2000);
    return true;
  } catch {
    return false;
  }
}

// If the supportdesk:// deep link did not actually open THIS project's own
// mobile app (the page is still foregrounded a few seconds after the launch
// attempt), surface an honest install nudge instead of leaving the customer
// on a dead page. This is the exact gap that otherwise pushes them to open the
// real ConnectWise Control app, which crashes against this non-ScreenConnect
// relay with "null is not an object (evaluating 'browsershare.hidden = isMobile')".
function surfaceMobileAppInstallGuidance(delayMs = 3500) {
  if (!isMobilePlatform()) return;
  window.setTimeout(() => {
    if (document.hidden) return; // the native app opened and foregrounded itself
    const installUrl = pendingMobileSupport?.installUrl || '';
    if (installUrl) {
      if (mobileAppLink) {
        mobileAppLink.href = installUrl;
        mobileAppLink.textContent = `Install ${mobileAppName()}`;
      }
      if (controlMessage) {
        controlMessage.textContent = `If ${mobileAppName()} did not open, install it from the link above, open it, enter helpsupport.top and your support code, then tap Start Broadcast.`;
      }
    } else if (controlMessage) {
      controlMessage.textContent = `If ${mobileAppName()} did not open, install the ConnectWise app, open it, enter helpsupport.top and your support code, then tap Start Broadcast.`;
    }
  }, delayMs);
}

