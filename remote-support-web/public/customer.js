function isInThirdPartyWKWebView() {
  const ua = navigator.userAgent;
  if (!/iPhone|iPad|iPod/.test(ua)) return false;
  if (/CriOS\/|FxiOS\/|OPiOS\//.test(ua)) return false;
  return /AppleWebKit/.test(ua) && !(/Version\/\d/.test(ua) && /Safari\/\d/.test(ua));
}

// Returns the supportdesk://join deep link that launches THIS project's own
// mobile support app (registered for the `supportdesk` URL scheme). The app
// connects to our relay via WebSocket and streams screen.frame messages.
//
// IMPORTANT: never use screenconnect:// here. That scheme launches the REAL
// ConnectWise Control app, which expects a genuine ScreenConnect server; when
// pointed at this custom relay its bundled guest JS crashes with
// "null is not an object (evaluating 'browsershare.hidden = isMobile')" because
// the server response shape is not ScreenConnect's. Use supportdesk:// instead.
function mobileAppDeepLink(sessionId, token) {
  if (pendingMobileSupport?.deepLinkScheme) return pendingMobileSupport.deepLinkScheme;
  try {
    const url = new URL('supportdesk://join');
    url.searchParams.set('server', stableOrigin());
    url.searchParams.set('sessionId', sessionId);
    url.searchParams.set('token', token);
    url.searchParams.set('platform', currentPlatform);
    url.searchParams.set('client', (currentPlatform === 'iphone' || currentPlatform === 'ipad') ? 'ios-mobile-broadcast' : 'android-mobile-broadcast');
    url.searchParams.set('broadcast', '1');
    return url.toString();
  } catch {
    return '';
  }
}

// Returns the shareable https://helpsupport.top/join native-app link (this
// project's public hostname). This is the link the customer copies / shares /
// taps from outside the site: it opens the native app via Universal Link (iOS)
// / App Link (Android) when the app is installed and registered for the
// helpsupport.top host, and otherwise loads /customer (customer.html) which
// auto-launches the app via the supportdesk:// scheme. Distinct from
// mobileAppDeepLink() (the supportdesk:// scheme used for reliable same-domain
// in-page launch, since a same-domain https navigation does not trigger iOS
// Universal Links).
function mobileAppShareLink(sessionId, token) {
  if (pendingMobileSupport?.deepLink) return pendingMobileSupport.deepLink;
  try {
    const base = stableOrigin();
    const url = new URL('/join', base);
    url.searchParams.set('server', base);
    url.searchParams.set('sessionId', sessionId);
    url.searchParams.set('token', token);
    url.searchParams.set('platform', currentPlatform);
    url.searchParams.set('client', (currentPlatform === 'iphone' || currentPlatform === 'ipad') ? 'ios-mobile-broadcast' : 'android-mobile-broadcast');
    url.searchParams.set('broadcast', '1');
    return url.toString();
  } catch {
    return '';
  }
}

